// Kho collocation IELTS theo chủ đề.
// Mỗi cụm có: nghĩa, cách dùng (cấu trúc ngữ pháp), ngữ cảnh sử dụng và câu mẫu.
// `alt` = các từ khác cũng kết hợp tự nhiên với vế phải (dùng để giải thích
// và để tránh đưa 2 cụm "nối chéo được" vào cùng một ván game).

export interface Collocation {
  id: string;
  left: string;
  right: string;
  vi: string;
  topic: string;
  usage: string;
  context: string;
  examples: string[];
  alt?: string[];
}

type Row = [
  left: string,
  right: string,
  vi: string,
  usage: string,
  context: string,
  examples: string[],
  alt?: string[]
];

function build(topic: string, rows: Row[]): Collocation[] {
  return rows.map(([left, right, vi, usage, context, examples, alt]) => ({
    id: `${left}-${right}`.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, ""),
    left,
    right,
    vi,
    topic,
    usage,
    context,
    examples,
    alt,
  }));
}

